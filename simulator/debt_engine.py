def print_debt_summary(
    loan,
    schedule,
):
    """Print debt schedule summary."""

    print("\n" + "=" * 70)
    print("FINSHIELD DEBT ENGINE")
    print("=" * 70)

    print(
        f"Loan ID: "
        f"{loan['loan_id']}"
    )

    print(
        f"Principal: "
        f"₹{loan['principal']:,.0f}"
    )

    print(
        f"Annual interest rate: "
        f"{loan['annual_interest_rate'] * 100:.2f}%"
    )

    print(
        f"Tenure: "
        f"{loan['tenure_months']} months"
    )

    print(
        f"Scheduled EMI: "
        f"₹{loan['emi']:,.0f}"
    )

    print(
        f"\nMonths simulated: "
        f"{len(schedule)}"
    )

    total_interest = sum(
        row["interest_payment"]
        for row in schedule
    )

    total_principal = sum(
        row["principal_payment"]
        for row in schedule
    )

    total_payments = sum(
        row["scheduled_emi"]
        for row in schedule
    )

    print(
        f"Interest paid in simulation: "
        f"₹{total_interest:,.0f}"
    )

    print(
        f"Principal paid in simulation: "
        f"₹{total_principal:,.0f}"
    )

    print(
        f"Total debt payments: "
        f"₹{total_payments:,.0f}"
    )

    print("\nFirst 6 months:")

    for row in schedule[:6]:

        print(
            f"  {row['month']} | "
            f"EMI ₹{row['scheduled_emi']:,.0f} | "
            f"Interest ₹{row['interest_payment']:,.0f} | "
            f"Principal ₹{row['principal_payment']:,.0f} | "
            f"Remaining ₹{row['ending_debt_balance']:,.0f}"
        )

    print("\nLast simulated month:")

    last = schedule[-1]

    print(
        f"  {last['month']} | "
        f"Remaining debt "
        f"₹{last['ending_debt_balance']:,.0f}"
    )

    print("=" * 70)


